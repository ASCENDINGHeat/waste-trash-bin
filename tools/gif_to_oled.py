#!/usr/bin/env python3
"""
Convert any animated GIF into main/dancing_cat_frames.h for the 128x64 I2C OLED
(SSD1306 / SH1106 vertical page-addressed format: 1024 bytes per frame).

Usage:
    python3 tools/gif_to_oled.py assets/dancing_cat.gif -o main/dancing_cat_frames.h
    python3 tools/gif_to_oled.py assets/dancing_cat.gif -o main/dancing_cat_frames.h --dither --invert
"""

import argparse
import os
import sys
from PIL import Image, ImageOps, ImageSequence

OLED_WIDTH = 128
OLED_HEIGHT = 64
OLED_FRAME_BYTES = (OLED_WIDTH * OLED_HEIGHT) // 8  # 1024 bytes


def frame_to_ssd1306_page_bytes(img_1bit: Image.Image) -> bytes:
    """
    Pack a 128x64 1-bit PIL Image into SSD1306 page-addressed format:
    8 pages (rows of 8 vertical pixels) x 128 columns = 1024 bytes.
    Bit 0 (LSB) is the top pixel of the page; Bit 7 (MSB) is the bottom pixel.
    """
    pixels = img_1bit.load()
    buf = bytearray(OLED_FRAME_BYTES)
    for page in range(OLED_HEIGHT // 8):
        for x in range(OLED_WIDTH):
            byte_val = 0
            for bit in range(8):
                y = page * 8 + bit
                if pixels[x, y] != 0:
                    byte_val |= (1 << bit)
            buf[page * OLED_WIDTH + x] = byte_val
    return bytes(buf)


def process_gif(
    gif_path: str,
    threshold: int = 128,
    dither: bool = False,
    invert: bool = False,
    stretch: bool = False,
    max_frames: int = 80,
) -> list[bytes]:
    im = Image.open(gif_path)
    frames_bytes: list[bytes] = []

    raw_frames = [f.copy().convert("RGBA") for f in ImageSequence.Iterator(im)]
    total = len(raw_frames)
    step = max(1, total // max_frames) if total > max_frames else 1

    for idx in range(0, total, step):
        if len(frames_bytes) >= max_frames:
            break
        rgba = raw_frames[idx]

        # Composite transparent pixels onto black background
        bg = Image.new("RGBA", rgba.size, (0, 0, 0, 255))
        composited = Image.alpha_composite(bg, rgba).convert("L")

        if invert:
            composited = ImageOps.invert(composited)

        # Resize to 128x64 (either aspect-ratio centered or stretched)
        if stretch:
            resized = composited.resize((OLED_WIDTH, OLED_HEIGHT), Image.Resampling.LANCZOS)
        else:
            resized = Image.new("L", (OLED_WIDTH, OLED_HEIGHT), 0)
            thumb = composited.copy()
            thumb.thumbnail((OLED_WIDTH, OLED_HEIGHT), Image.Resampling.LANCZOS)
            offset_x = (OLED_WIDTH - thumb.width) // 2
            offset_y = (OLED_HEIGHT - thumb.height) // 2
            resized.paste(thumb, (offset_x, offset_y))

        # Convert grayscale to 1-bit monochrome
        if dither:
            bw = resized.convert("1", dither=Image.Dither.FLOYDSTEINBERG)
        else:
            bw = resized.point(lambda p: 255 if p >= threshold else 0, mode="1")

        frames_bytes.append(frame_to_ssd1306_page_bytes(bw))

    return frames_bytes


def write_header(frames: list[bytes], out_path: str, src_name: str) -> None:
    num_frames = len(frames)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/gif_to_oled.py from %s */\n" % src_name)
        f.write("#ifndef DANCING_CAT_FRAMES_H\n")
        f.write("#define DANCING_CAT_FRAMES_H\n\n")
        f.write("#include <stdint.h>\n")
        f.write("#include <string.h>\n\n")
        f.write("#define OLED_WIDTH              128\n")
        f.write("#define OLED_HEIGHT             64\n")
        f.write("#define OLED_PAGES              (OLED_HEIGHT / 8)\n")
        f.write("#define OLED_FRAME_BYTES        (OLED_WIDTH * OLED_PAGES)\n")
        f.write(f"#define DANCING_CAT_NUM_FRAMES  {num_frames}\n\n")
        f.write("static const uint8_t s_dancing_cat_gif_bitmap[DANCING_CAT_NUM_FRAMES][OLED_FRAME_BYTES] = {\n")
        for i, frame in enumerate(frames):
            f.write(f"    /* Frame {i} */\n    {{\n        ")
            hex_items = [f"0x{b:02X}" for b in frame]
            for j in range(0, len(hex_items), 16):
                chunk = ", ".join(hex_items[j : j + 16])
                if j + 16 < len(hex_items):
                    f.write(chunk + ",\n        ")
                else:
                    f.write(chunk + "\n")
            f.write("    },\n")
        f.write("};\n\n")
        f.write("static inline void dancing_cat_render_frame(uint8_t *buf, int frame_idx)\n")
        f.write("{\n")
        f.write("    int idx = frame_idx % DANCING_CAT_NUM_FRAMES;\n")
        f.write("    memcpy(buf, s_dancing_cat_gif_bitmap[idx], OLED_FRAME_BYTES);\n")
        f.write("}\n\n")
        f.write("#endif /* DANCING_CAT_FRAMES_H */\n")


def main() -> None:
    parser = argparse.ArgumentParser(description="Convert GIF to 128x64 SSD1306 C header")
    parser.add_argument("gif", help="Path to input .gif file")
    parser.add_argument("-o", "--output", default="main/dancing_cat_frames.h", help="Output C header path")
    parser.add_argument("-t", "--threshold", type=int, default=128, help="Monochrome threshold 0-255 (default: 128)")
    parser.add_argument("--dither", action="store_true", help="Use Floyd-Steinberg 1-bit dithering")
    parser.add_argument("--invert", action="store_true", help="Invert black and white pixels")
    parser.add_argument("--stretch", action="store_true", help="Stretch GIF to fill 128x64 instead of letterboxing")
    parser.add_argument("--max-frames", type=int, default=80, help="Maximum number of frames to extract")
    args = parser.parse_args()

    if not os.path.isfile(args.gif):
        print(f"Error: GIF file not found: {args.gif}", file=sys.stderr)
        sys.exit(1)

    frames = process_gif(
        args.gif,
        threshold=args.threshold,
        dither=args.dither,
        invert=args.invert,
        stretch=args.stretch,
        max_frames=args.max_frames,
    )
    write_header(frames, args.output, os.path.basename(args.gif))
    print(f"Converted {len(frames)} frames ({len(frames) * OLED_FRAME_BYTES} bytes) -> {args.output}")


if __name__ == "__main__":
    main()
